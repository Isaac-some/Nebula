import { test, expect } from "@playwright/test";
import JSZip from "jszip";
import fs from "node:fs/promises";

test.skip(process.env.ATLAS_BROWSER_DEMO !== "true", "Browser-only export acceptance");

test("个人 Demo 的保存、搜索、编辑、导出导入、隔离与删除", async ({ page, browser, baseURL }) => {
  const errors: string[] = [], apiRequests: string[] = [];
  page.on("pageerror", e => errors.push(e.message));
  page.on("request", r => { if (r.url().includes("/api/")) apiRequests.push(r.url()); });
  await page.goto("./");
  await expect(page.locator(".graph-node")).toHaveCount(56);
  const title = "Demo 持久化验收";
  await page.getByRole("button", {name:"新建文档",exact:true}).click();
  await page.getByLabel("知识点标题",{exact:true}).fill(title);
  await page.locator("#note-summary").fill("保存后刷新仍应保留");
  await page.locator(".tiptap").fill("关联 [[AI Agent]]，浏览器独立保存。");
  await page.getByRole("button",{name:"保存知识点",exact:true}).click();
  await expect(page.getByRole("status")).toContainText("已保存");
  await page.reload();
  const node = page.locator(`.graph-node[data-note-title="${title}"]`);
  await expect(node).toHaveCount(1);
  // A separate browser context gets its own example vault.
  const other = await browser.newContext();
  const second = await other.newPage();
  await second.goto(baseURL!);
  await expect(second.locator(".graph-node")).toHaveCount(56);
  await expect(second.locator(`.graph-node[data-note-title="${title}"]`)).toHaveCount(0);
  await other.close();
  await page.keyboard.press("ControlOrMeta+k");
  await page.getByLabel("搜索知识库",{exact:true}).fill(title);
  await page.locator(".search-hit").filter({hasText:title}).click();
  await expect(page.locator(".reading-paper")).toContainText("浏览器独立保存");
  await page.getByRole("button",{name:"收藏文档",exact:true}).click();
  await expect(page.getByRole("button",{name:"取消收藏",exact:true})).toBeVisible();
  await page.getByRole("button",{name:"编辑",exact:true}).click();
  await page.locator("#note-summary").fill("编辑后的摘要");
  await page.getByRole("button",{name:"保存知识点",exact:true}).click();
  await page.reload();
  await expect(page.locator(".reading-paper")).toContainText("编辑后的摘要");
  await page.locator(".settings-link").click();
  await expect(page.locator(".settings-modal")).toContainText("当前浏览器");
  const downloadPromise = page.waitForEvent("download");
  await page.getByRole("button",{name:"导出全部文档",exact:true}).click();
  const download = await downloadPromise;
  expect(download.suggestedFilename()).toBe("nebula-vault.zip");
  const zip = await JSZip.loadAsync(await fs.readFile((await download.path())!));
  const file = Object.values(zip.files).find(f=>f.name.endsWith(`/${title}.md`))!;
  const markdown = await file.async("string");
  expect(markdown).toContain("编辑后的摘要");
  await page.getByLabel("关闭设置",{exact:true}).click();
  page.on("dialog",d=>d.accept());
  await page.getByRole("button",{name:"删除文档",exact:true}).click();
  await page.reload();
  await expect(node).toHaveCount(0);
  await page.locator('input[type="file"]').setInputFiles({name:`${title}.md`,mimeType:"text/markdown",buffer:Buffer.from(markdown)});
  await expect(page.getByRole("status")).toContainText("已导入 1 篇");
  await page.reload();
  await expect(node).toHaveCount(1);
  expect(apiRequests).toEqual([]);
  expect(errors).toEqual([]);
});
